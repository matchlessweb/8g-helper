// Copies the GridPane commands from the 8G for GridPane runbook into src/content/runbook.ts, so the guide on the page
// is exactly what was run and tested. Run: node scripts/import-runbook.mjs <path to docs/runbook.md> <source label>
import { readFileSync, writeFileSync } from 'node:fs'

const [path, source] = process.argv.slice(2)
if (!path || !source) throw new Error('usage: node scripts/import-runbook.mjs <runbook.md> <source label>')
const md = readFileSync(path, 'utf8')

/** The n-th ```sh block under the heading that starts with `heading`. */
function block(heading, n = 1) {
  const sections = md.split(/^## /m)
  const section = sections.find((s) => s.startsWith(heading))
  if (!section) throw new Error(`no section "${heading}"`)
  const blocks = [...section.matchAll(/^```sh\n([\s\S]*?)^```$/gm)].map((m) => m[1].trimEnd())
  if (!blocks[n - 1]) throw new Error(`no block ${n} under "${heading}"`)
  return blocks[n - 1]
}

const RUNBOOK = {
  check: block('Step 0.'),
  download: block('Step 1.'),
  watch: block('Step 2.'),
  verify: block('Step 3.'),
  read: block('Step 4.'),
  enforce: block('Step 5.', 1),
  prove: block('Step 5.', 2),
  undo: block('Undo'),
}

writeFileSync(
  new URL('../src/content/runbook.ts', import.meta.url),
  `// Generated by scripts/import-runbook.mjs from ${source}. Do not edit by hand.\n` +
    `export const RUNBOOK = ${JSON.stringify(RUNBOOK, null, 2)} as const\n`,
)
console.log(`runbook.ts: ${Object.keys(RUNBOOK).length} blocks from ${source}`)
