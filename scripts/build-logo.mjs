// Builds the 7G Helper logo from IBM Plex outlines, so it renders the same everywhere, with no font loaded:
// the lockup ([7G] Helper) as a React-ready path module, the app icon (7G knocked out of a teal tile) as the
// favicon and the 180px touch icon, and standalone SVGs in brand/. Run: node scripts/build-logo.mjs
import { writeFileSync } from 'node:fs'
import opentype from 'opentype.js'
import sharp from 'sharp'

const root = new URL('../', import.meta.url)
const font = (p) => opentype.loadSync(new URL(`node_modules/@fontsource/${p}`, root).pathname)
const mono = font('ibm-plex-mono/files/ibm-plex-mono-latin-700-normal.woff')
const sans = font('ibm-plex-sans/files/ibm-plex-sans-latin-600-normal.woff')
const d = (f, text, x, y, size) => f.getPath(text, x, y, size).toPathData(2)
const box = (f, text, size) => f.getPath(text, 0, 0, size).getBoundingBox()

// Lockup, 40 units high: [ 7G ] then Helper on the same baseline.
const H = 40
const base = 29.5
const g = box(mono, '7G', 28)
const pad = 7.5
const inner = g.x2 - g.x1 + pad * 2
const bx = 2
const sevenG = d(mono, '7G', bx + pad - g.x1, base, 28)
const brackets = `M${bx + 5.5} 5.5H${bx}V${H - 5.5}H${bx + 5.5}M${bx + inner - 5.5} 5.5H${bx + inner}V${H - 5.5}H${bx + inner - 5.5}`
const hx = bx + inner + 10
const helper = d(sans, 'Helper', hx, base, 27)
const width = Math.ceil(hx + sans.getAdvanceWidth('Helper', 27) + 1)

writeFileSync(
  new URL('src/brand/logoPaths.ts', root),
  `// Generated by scripts/build-logo.mjs from IBM Plex Mono 700 and IBM Plex Sans 600. Do not edit by hand.\n` +
    `export const LOGO = ${JSON.stringify({ width, height: H, brackets, bracketStroke: 3, sevenG, helper }, null, 2)} as const\n`,
)

const lockup = (accent, text) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${H}" width="${width * 2}" height="${H * 2}" role="img" aria-label="7G Helper">` +
  `<path d="${brackets}" fill="none" stroke="${accent}" stroke-width="3" stroke-linecap="square"/>` +
  `<path d="${sevenG}" fill="${text}"/><path d="${helper}" fill="${text}"/></svg>\n`
writeFileSync(new URL('brand/logo-light.svg', root), lockup('#0b6e5f', '#14212b'))
writeFileSync(new URL('brand/logo-dark.svg', root), lockup('#5fd0bc', '#e8eef2'))

// App icon: 7G knocked out of a teal tile, 48 units square.
const ig = box(mono, '7G', 25)
const ix = (48 - (ig.x2 - ig.x1)) / 2 - ig.x1
const iy = (48 - (ig.y2 - ig.y1)) / 2 - ig.y1
const icon = (size) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" width="${size}" height="${size}" role="img" aria-label="7G Helper">` +
  `<rect width="48" height="48" rx="11" fill="#0b6e5f"/><path d="${d(mono, '7G', ix, iy, 25)}" fill="#ffffff"/></svg>\n`
writeFileSync(new URL('public/favicon.svg', root), icon(48))
writeFileSync(new URL('brand/icon.svg', root), icon(512))
await sharp(Buffer.from(icon(180))).png().toFile(new URL('public/apple-touch-icon.png', root).pathname)
console.log(`logo ${width}x${H}; favicon, touch icon and brand/ SVGs written`)
